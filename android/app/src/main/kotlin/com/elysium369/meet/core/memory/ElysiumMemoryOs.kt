// ─── Memory Classification ───

enum class MemoryClass(val description: String) {
    IDENTITY("Quién soy, datos personales, preferencias fundamentales"),
    EPISODIC("Eventos vividos, experiencias, contextos"),
    SEMANTIC("Hechos conocidos, conceptos aprendidos, información general"),
    PROCEDURAL("Habilidades, cómo hacer cosas, recetas, workflows"),
    GOALS("Metas activas, planes, aspiraciones"),
    LEARNING("Progreso educativo, mastery states, conceptos por aprender"),
    MASTERY_EVIDENCE("Evidencia de competencia demostrada"),
    PROJECT_HISTORY("Proyectos activos y pasados, trabajo realizado"),
    ECONOMIC("Historial laboral, financiero, profesional"),
    PREFERENCES("Gustos, configuraciones, patrones de uso"),
    RELATIONAL("Conexiones con personas, empresas, instituciones"),
}

enum class MemoryConfidence {
    AUTHORITATIVE,  // Official document, verified measurement
    HIGH,           // Multiple consistent observations
    MODERATE,       // Single observation, no contradiction
    LOW,            // Inferred or reported without verification
    CONTESTED,      // Contradicted by newer evidence
    SUPERSEDED,     // Replaced by fresher entry
}

enum class MemoryProvenance {
    USER_EXPLICIT,        // User said "remember this"
    SYSTEM_OBSERVED,      // Platform observed this from user behavior
    LEARNING_ENGINE,      // Generated by mastery/FSRS engine
    ECONOMIC_ENGINE,      // Generated by service/job completion
    OPENCLAW_WIKI,        // Synced from OpenClaw Memory-Wiki
    EXTERNAL_IMPORT,      // Imported from Obsidian/files/API
    AI_INFERRED,          // AI derived this (lower trust)
    CONSOLIDATION,        // Generated during memory consolidation ("dreaming")
}

// ─── Memory Entry (atomic unit) ───

@Serializable
data class MemoryEntry(
    val id: String,
    val namespace: String,
    val memoryClass: MemoryClass,
    val key: String,
    val value: String,
    val confidence: MemoryConfidence = MemoryConfidence.MODERATE,
    val provenance: MemoryProvenance = MemoryProvenance.USER_EXPLICIT,
    val evidenceRefs: List<String> = emptyList(),
    val tags: List<String> = emptyList(),
    val createdAtEpochMs: Long = System.currentTimeMillis(),
    val updatedAtEpochMs: Long = System.currentTimeMillis(),
    val expiresAtEpochMs: Long? = null,
    val supersededById: String? = null,
    val version: Int = 1,
) {
    val isActive: Boolean
        get() = supersededById == null &&
            (expiresAtEpochMs == null || expiresAtEpochMs > System.currentTimeMillis())

    val isFresh: Boolean
        get() {
            val ageMs = System.currentTimeMillis() - updatedAtEpochMs
            val oneYearMs = 365L * 24 * 60 * 60 * 1000
            return ageMs < oneYearMs
        }
}

