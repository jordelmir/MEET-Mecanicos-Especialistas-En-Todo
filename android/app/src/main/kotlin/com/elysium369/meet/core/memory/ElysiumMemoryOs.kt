// ─── Memory Provider Interface (§69 model independence) ───

/**
 * Abstract interface for memory storage. Implementations:
 * - LocalSqliteMemoryProvider (offline-first, Room)
 * - OpenClawMemoryProvider (OpenClaw Memory-Wiki gateway)
 * - SupabaseMemoryProvider (cloud sync)
 *
 * Changing the provider MUST NOT erase accumulated memory (§69).
 */
interface MemoryProvider {
    val providerId: String

    suspend fun store(entry: MemoryEntry): MemoryEntry
    suspend fun retrieve(id: String): MemoryEntry?
    suspend fun query(query: MemoryQuery): List<MemoryEntry>
    suspend fun supersede(existingId: String, newEntry: MemoryEntry): MemoryEntry
    suspend fun delete(id: String): Boolean
    suspend fun export(namespace: String): List<MemoryEntry>
    suspend fun importEntries(entries: List<MemoryEntry>): Int
    suspend fun detectContradictions(namespace: String): List<MemoryContradiction>
    suspend fun consolidate(namespace: String): MemoryConsolidationEvent
}

